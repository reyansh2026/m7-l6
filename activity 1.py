from tkinter import *
from tkinter import messagebox
from tkinter.font import Font
root=Tk()
root.title('Restaurant order manager')
root.geometry("500x420")
bg=PhotoImage(file="food.png")
bg2=Label(root,image=bg, width=500,height=10)
bg2.lower()
bg2.place(x=0,y=0, relwidth=1,relheight=1)
medium=Font(family="Times New Roman", size=20)
z=Label(text='', relief=RIDGE, fg='gray', bg='gray', width=60,height=22)
z.place(x=40,y=40)
a=Label(text='Place your order', font=medium,relief=GROOVE, fg='black', bg='lightgray', width=20)
a.place(x=110,y=60)
b=Label(text='Burger Combo ($3)',relief=RAISED, fg='black', bg='lightgray', width=14)
b.place(x=70,y=120)
c=Label(text='Pizza Combo ($4)',relief=RAISED, fg='black', bg='lightgray', width=14)
c.place(x=70,y=160)
d=Label(text='Fries ($0.95)',relief=RAISED, fg='black', bg='lightgray', width=14)
d.place(x=70,y=200)
e=Label(text='Pasta ($2)',relief=RAISED, fg='black', bg='lightgray', width=14)
e.place(x=70,y=240)
f=Label(text='Noodles ($2)',relief=RAISED, fg='black', bg='lightgray', width=14)
f.place(x=70,y=280)
g=Entry(relief=SUNKEN, fg='black', bg='lightgray', width=17)
g.place(x=300,y=120)
h=Entry(relief=SUNKEN, fg='black', bg='lightgray', width=17)
h.place(x=300,y=160)
i=Entry(relief=SUNKEN, fg='black', bg='lightgray', width=17)
i.place(x=300,y=200)
j=Entry(relief=SUNKEN, fg='black', bg='lightgray', width=17)
j.place(x=300,y=240)
k=Entry(relief=SUNKEN, fg='black', bg='lightgray', width=17)
k.place(x=300,y=280)
def hi():
    m=int(g.get())
    n=int(h.get())
    o=int(i.get())
    p=int(j.get())
    q=int(k.get())
    total=(m*3)+(n*4)+(o*0.95)+(p*2)+(q*2)
    messagebox.showinfo("The total", f"The total bill for your order will be ${total}")
l=Button(text='Calculate Total',relief=RAISED, command=hi,fg='black', bg='green', width=17)
l.place(x=185,y=330)
root.mainloop()
